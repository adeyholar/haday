import assert from "node:assert/strict";
import test from "node:test";
import { createJiti } from "jiti";

const jiti = createJiti(import.meta.url, { alias: { "@": new URL("../src", import.meta.url).pathname } });
const { itemsForWeek, bbhVocab } = await jiti.import(new URL("../src/lib/vocab.ts", import.meta.url).pathname);
const { VOCAB_S2, itemsForTerm2Week, isTerm2Week, TERM2_WEEKS, weekForTerm2Chapter } = await jiti.import(new URL("../src/lib/vocab-s2.ts", import.meta.url).pathname);
const { TERM2_LESSONS } = await jiti.import(new URL("../src/lib/term2-lessons.ts", import.meta.url).pathname);
const { secondTermBlock } = await jiti.import(new URL("../src/lib/path.ts", import.meta.url).pathname);

test("semester 2 words stay off the first-term list", () => {
  assert.equal(VOCAB_S2.length, 206);
  assert.ok(VOCAB_S2.every((item) => item.id.startsWith("s2-")));
  assert.equal(bbhVocab().some((item) => item.id.startsWith("s2-")), false);
  assert.equal(itemsForWeek(1).some((item) => item.id.startsWith("s2-")), false);
  const chapter20 = itemsForWeek(101);
  assert.ok(chapter20.length > 0);
  assert.ok(chapter20.every((item) => item.chapter === 20));
  assert.equal(TERM2_WEEKS.length, 16);
  assert.ok(TERM2_WEEKS.every((row) => row.chapters.length === 1 && !row.label.startsWith("Week")));
  assert.equal(weekForTerm2Chapter(24), 105);
  assert.ok(itemsForWeek(105).every((item) => item.chapter === 24));
  assert.equal(weekForTerm2Chapter(35), 116);
  assert.ok(itemsForTerm2Week(116).every((item) => item.chapter === 35));
  assert.equal(isTerm2Week(101), true);
  assert.equal(isTerm2Week(116), true);
  assert.equal(isTerm2Week(15), false);
  assert.equal(isTerm2Week(112), true);
  const pala = VOCAB_S2.filter((item) => item.hebrew.includes("פָּלָא") || item.hebrew.includes("פָּלָא"));
  assert.equal(pala.length, 2);
  assert.equal(itemsForTerm2Week(weekForTerm2Chapter(24)).filter((item) => item.hebrew.includes("לָא")).length, 1);
  assert.equal(secondTermBlock("/drill", 2), null);
  assert.equal(secondTermBlock("/game", 2), "/bbh");
  assert.equal(secondTermBlock("/game/week7", 2), "/bbh");
  assert.equal(secondTermBlock("/game/road", 2), "/bbh");
  assert.equal(secondTermBlock("/game/final", 2), "/bbh");
  assert.equal(secondTermBlock("/game/final-vocab", 2), "/bbh");
  assert.equal(secondTermBlock("/challenge", 2), "/bbh");
  assert.equal(secondTermBlock("/game/verbal-system", 2), null);
  assert.equal(secondTermBlock("/game/verb-paradigm-quest", 2), null);
  assert.equal(secondTermBlock("/game/qal-perfect", 2), null);
  assert.equal(secondTermBlock("/game/lessons/verbs", 2), null);
  assert.equal(secondTermBlock("/game/lessons/verbs/3", 2), null);
  assert.equal(secondTermBlock("/game/lessons/prep", 2), "/bbh");
  assert.equal(secondTermBlock("/lessons/verbs", 2), null);
  assert.equal(TERM2_LESSONS.length, 16);
  assert.equal(TERM2_LESSONS[0].chapter, 20);
  assert.equal(TERM2_LESSONS[15].chapter, 35);
  assert.equal(VOCAB_S2.some((item) => item.gloss.includes("cs)")), false);
  assert.equal(VOCAB_S2.filter((item) => item.hebrew === "אֲרוֹן").length, 1);
});
